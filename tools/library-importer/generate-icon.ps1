param(
    [string]$Source = (Join-Path $PSScriptRoot "..\logo\sc64_logo.png"),
    [string]$Destination = (Join-Path $PSScriptRoot "src\icon.zig")
)

$ErrorActionPreference = "Stop"
Add-Type -AssemblyName System.Drawing

$sourceImage = [System.Drawing.Bitmap]::FromFile($Source)
try {
    # Exact alpha bounds of the S and C components. A wider rectangular crop also
    # catches the first anti-aliased column of the 6, which becomes visible as a
    # stray mark at icon scale.
    $crop = [System.Drawing.Rectangle]::new(14, 38, 424, 142)
    $sizes = @(16, 32, 64, 128)
    $output = [System.Text.StringBuilder]::new()
    $null = $output.AppendLine("// Generated by generate-icon.ps1 from tools/logo/sc64_logo.png.")
    $null = $output.AppendLine("const sapp = @import(`"sokol`" ).app;")
    $null = $output.AppendLine()

    foreach ($size in $sizes) {
        $bitmap = [System.Drawing.Bitmap]::new($size, $size, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
        try {
            $graphics = [System.Drawing.Graphics]::FromImage($bitmap)
            try {
                $graphics.Clear([System.Drawing.Color]::FromArgb(255, 12, 5, 28))
                $graphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBilinear
                $graphics.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
                $margin = [Math]::Max(1, [int]($size * 0.08))
                $targetWidth = $size - ($margin * 2)
                $targetHeight = [int][Math]::Round($targetWidth * $crop.Height / $crop.Width)
                $targetY = [int](($size - $targetHeight) / 2)

                # Keyline: draw the white alpha mask in black around eight neighbours.
                $attributes = [System.Drawing.Imaging.ImageAttributes]::new()
                try {
                    $matrix = [System.Drawing.Imaging.ColorMatrix]::new([single[][]]@(
                        [single[]]@(0,0,0,0,0), [single[]]@(0,0,0,0,0), [single[]]@(0,0,0,0,0),
                        [single[]]@(0,0,0,1,0), [single[]]@(0,0,0,0,1)
                    ))
                    $attributes.SetColorMatrix($matrix)
                    $stroke = [Math]::Max(1, [int]($size / 32))
                    foreach ($dx in @(-$stroke, 0, $stroke)) {
                        foreach ($dy in @(-$stroke, 0, $stroke)) {
                            if ($dx -eq 0 -and $dy -eq 0) { continue }
                            $graphics.DrawImage($sourceImage, [System.Drawing.Rectangle]::new($margin + $dx, $targetY + $dy, $targetWidth, $targetHeight), $crop.X, $crop.Y, $crop.Width, $crop.Height, [System.Drawing.GraphicsUnit]::Pixel, $attributes)
                        }
                    }
                }
                finally { $attributes.Dispose() }

                # Draw the silhouette three times through horizontal clips.
                foreach ($band in @(
                    @{ Top = 0.00; Bottom = 0.44; Color = [System.Drawing.Color]::FromArgb(255,255,214,0) },
                    @{ Top = 0.44; Bottom = 0.74; Color = [System.Drawing.Color]::FromArgb(255,255,122,0) },
                    @{ Top = 0.74; Bottom = 1.00; Color = [System.Drawing.Color]::FromArgb(255,255,35,156) }
                )) {
                    $graphics.SetClip([System.Drawing.Rectangle]::new(0, $targetY + [int]($targetHeight * $band.Top), $size, [Math]::Max(1, [int]($targetHeight * ($band.Bottom - $band.Top)) + 1)))
                    $attributes = [System.Drawing.Imaging.ImageAttributes]::new()
                    try {
                        $r = $band.Color.R / 255.0; $g = $band.Color.G / 255.0; $b = $band.Color.B / 255.0
                        $matrix = [System.Drawing.Imaging.ColorMatrix]::new([single[][]]@(
                            [single[]]@($r,0,0,0,0), [single[]]@(0,$g,0,0,0), [single[]]@(0,0,$b,0,0),
                            [single[]]@(0,0,0,1,0), [single[]]@(0,0,0,0,1)
                        ))
                        $attributes.SetColorMatrix($matrix)
                        $graphics.DrawImage($sourceImage, [System.Drawing.Rectangle]::new($margin, $targetY, $targetWidth, $targetHeight), $crop.X, $crop.Y, $crop.Width, $crop.Height, [System.Drawing.GraphicsUnit]::Pixel, $attributes)
                    }
                    finally { $attributes.Dispose() }
                    $graphics.ResetClip()
                }
            }
            finally { $graphics.Dispose() }

            $null = $output.AppendLine("pub const rgba_$size = [$($size * $size * 4)]u8{")
            for ($y = 0; $y -lt $size; $y++) {
                $null = $output.Append("    ")
                for ($x = 0; $x -lt $size; $x++) {
                    $pixel = $bitmap.GetPixel($x, $y)
                    $null = $output.Append("$($pixel.R),$($pixel.G),$($pixel.B),$($pixel.A),")
                }
                $null = $output.AppendLine()
            }
            $null = $output.AppendLine("};")
            $null = $output.AppendLine()
        }
        finally { $bitmap.Dispose() }
    }

    $null = $output.AppendLine("pub fn desc() sapp.IconDesc {")
    $null = $output.AppendLine("    var icon: sapp.IconDesc = .{};")
    for ($index = 0; $index -lt $sizes.Count; $index++) {
        $size = $sizes[$index]
        $null = $output.AppendLine("    icon.images[$index] = .{ .width = $size, .height = $size, .pixels = .{ .ptr = &rgba_$size, .size = rgba_$size.len } };")
    }
    $null = $output.AppendLine("    return icon;")
    $null = $output.AppendLine("}")

    [System.IO.File]::WriteAllText($Destination, $output.ToString(), [System.Text.UTF8Encoding]::new($false))
    & zig fmt $Destination | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "zig fmt failed for generated icon" }
}
finally { $sourceImage.Dispose() }
